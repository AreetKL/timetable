/** 随机取一句，尽量别和上一句重复。 */
fun randomPoem(exclude: PoemLine? = null): PoemLine {
    if (POEMS.size <= 1) return POEMS.first()
    var p = POEMS.random()
    var guard = 0
    while (p == exclude && guard++ < 8) p = POEMS.random()
    return p
}
